"""\brief Calculate semiconductor losses with IEC TC 22 formulas.

This module is part of the PELCA reliability evaluator.
"""

# note: the standard gives formulas to determine the avg losses (conduction / switching) affecting a device (diode / igbt)
# during one period of output current. The purpose is to enable calculation of losses of the whole inverter stage.
# Here we consider that each leg of inverter is composed of two HB connected in //. The losses are calculated for devices within on HB.

# possible enhancements: number of modules connected in // might be parameterized (1 .. N), data coming from Excel sheet
# m can possibly change depending on relative_speed parameter of mission profile => need to update m from class
# PF can also be modified depending on relative_torque requested


import math

class IEC_TC_22_calc_losses():

    """Represent i e c t c 22 calc losses behavior used by reliability calculations."""
    def __init__(self, fsw: int = 2000, PF: float=0.8, m: float=0.7, nb_parallel_modules=2):
        """Initialize the object with the provided configuration."""
        self.fsw = fsw
        self.PF  = PF
        self.m   = m
        self.nb_parallel_modules = nb_parallel_modules

    # ==============================================================================================
    # assumption : two HB modules in parallel (per leg) => full inverter: 3 legs <=> 6 half bridges
    # ==============================================================================================
    # returns the avg losses for one HB, over one period of output current:
    #  PL_on_T_HB : on-state losses of one transistor of one half bridge
    #  PL_on_D_HB : on-state losses of one diode of one half bridge
    #  PL_sw_T_HB : switching losses of one transistor of one half bridge
    #  PL_sw_D_HB : switching losses (recovery) of one diode of one half-bridge
    #
    # 2 diodes & 2 transistors per half-bridge module
    # => total losses per power module = 2*(PL_on_T_HB+PL_on_D_HB+PL_sw_T_HB+PL_sw_D_HB)
    #
    # total losses generated by the 6 power modules: 12*(PL_on_T_HB+PL_on_D_HB+PL_sw_T_HB+PL_sw_D_HB)

    def calc_losses(self, m, Iout, Ir_out, Udc, UT_th, UT_r, UD_th, UD_r, ET, ED):
        """

        Parameters
        ----------
        m : float
            modulation index.
        Iout : float
            inverter output current.
        Ir_out : float
            inverter output rated current.
        Udc : float
            DC bus voltage.
        UT_th : float
            IGBT threshold voltage (on characteristic).
        UT_r : float
            on state dynamic resistance.
        UD_th : float
            diode threshold voltage (during conduction of diode).
        UD_r : float
            on state dynamic resistance
        ET : float
            igbt (transistor) switching energy.
        ED : float
            diode switching energy.

        Returns
        -------
        PL_on_T_HB : float
            DESCRIPTION.
        PL_on_D_HB : float
            DESCRIPTION.
        PL_sw_T_HB : float
            DESCRIPTION.
        PL_sw_D_HB : float
            DESCRIPTION.

        """
        fsw=self.fsw  # params.get('fsw', 2000)
        # 4 000 for a CDM up to 90 kW
        # 2 000 for a CDM above 90 kW

        PF = self.PF  # params.get('PF', 0.8)

        # validity: pwm freq >= 15 ... 20 x fundamental freq of motor current
        #
        # calculation according to IEC-TC_1.pdf (p85...)
        sqrt2 =  math.sqrt(2)
        cos_phy=PF # phy=phase angle between fundamental of voltage & current motor

        # !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
        # m=self.m   # 0.7 # modulation index, supposed to be identical to the relative CDM output freq up to rated output freq
        # !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

        # Motor cable current, relevant for increased switching losses
        # Imotor_cable changes with motor current
        # Imotor_cable= params.get('Imotor_cable', 10)
        if Iout<4:
            Imotor_cable = 4 # Imotor_cable = 4 for Ir,out <= 4 A
        else:
            if Iout<10:
                Imotor_cable = Iout # Imotor_cable = ir,out for 4 A < Ir,out < 10 A
            else:
                Imotor_cable=10 # Imotor_cable = 10 for Ir,out >= 10 A

        # !!!!!!!!!!!!!!
        Imotor_cable = 0  # not considered for pwm estimation of losses
        # !!!!!!!!!!!!!!

        # calculation of losses according to IEC - TC 22-SC 22G

        # transistor on state losses
        PL_on_T    = (sqrt2*Iout*UT_th*(  (1/(2*math.pi))
                                        + (1.22*m*cos_phy)/8)
                      + ((UT_r-UT_th)/Ir_out) * 2*(Iout**2) * (1/8 + (1.22*m*cos_phy)/(3*math.pi))) # for single power module

        # <output current will be shared in 2 IGBT in //>
        PL_on_T_HB = (sqrt2*(Iout/self.nb_parallel_modules)*UT_th*(  (1/(2*math.pi))
                                                                   + (1.22*m*cos_phy)/8)
                      + ((UT_r-UT_th)/Ir_out) * 2*((Iout/self.nb_parallel_modules)**2) * (1/8 + (1.22*m*cos_phy)/(3*math.pi))) #

        # note: PL_on_T_HB != PL_on_T/2

        # freewheeling diode on state losses
        PL_on_D    = (sqrt2*Iout*UD_th*(  (1/(2*math.pi))
                                        - (1.22*m*cos_phy)/8)
                      + ((UD_r-UD_th)/Ir_out) * 2*(Iout**2) * (1/8 - (1.22*m*cos_phy)/(3*math.pi))) # for single power module

        # <output current will be shared in 2 diodes in //>
        PL_on_D_HB = (sqrt2*(Iout/self.nb_parallel_modules)*UD_th*(  (1/(2*math.pi))
                                                                   - (1.22*m*cos_phy)/8)
                      + ((UD_r-UD_th)/Ir_out) * 2*((Iout/self.nb_parallel_modules)**2) * (1/8 - (1.22*m*cos_phy)/(3*math.pi))) # in each HB
        # note: PL_on_D_HB != PL_on_D/2

        # transistor switching losses
        PL_sw_T    = (ET/math.pi) * Udc * sqrt2 * (Iout + Imotor_cable)*fsw             # for single power module

        # <output current will be shared in 2 IGBT in //>
        # PL_sw_T_HB = ET * Vdc * Idc_equ with Idc_equ = sqrt(2)*(Iout+Imotor_cable)/pi
        PL_sw_T_HB = (ET/math.pi) * Udc * sqrt2 * ((Iout/self.nb_parallel_modules) + (Imotor_cable/self.nb_parallel_modules))*fsw     # for each half bridge: PL_sw_T_HB (= PL_sw_T/2)

        # freewheeling diode switching losses
        PL_sw_D = (ED/math.pi) * Udc * sqrt2 * (Iout + Imotor_cable)*fsw                # for single power module

        # <output current will be shared in 2 diodes in //>
        PL_sw_D_HB = (ED/math.pi) * Udc * sqrt2 * ((Iout/self.nb_parallel_modules) + (Imotor_cable/self.nb_parallel_modules))*fsw     # PL_sw_D_HB = PL_sw_D/2

        return PL_on_T_HB, PL_on_D_HB, PL_sw_T_HB, PL_sw_D_HB


