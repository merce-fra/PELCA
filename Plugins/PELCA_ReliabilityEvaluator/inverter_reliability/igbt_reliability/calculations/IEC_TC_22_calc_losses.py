        # reference power module : Vec_terminals = 1.95V (@600A, Tvj=150degC)

        # for transistor switching losses calculation (J/VA)
        ET = reference_module.ET(Tj_igbt, Udc, Iout/nb_parallel_modules, reference_module.Rg)*1e-3  # Switching loss energy of the power transistor (IGBT) per volt and per ampere

        # for diode switching losses calculation (J/VA)
        ED = reference_module.ED(Tj_diode, Udc, Iout/nb_parallel_modules, reference_module.Rg)*1e-3  # Switching loss energy of the power diode per volt and per ampere

        # calculation of avg losses affecting one IGBT, one diode in a HB during a period of output current:
